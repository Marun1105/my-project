// config.js — един адрес на бекенда, споделен от всички frontend модули.
//
// Не се пипа на ръка. Досега тук пишеше „локално смени с 127.0.0.1“, а това
// искаше две неща наведнъж: да смениш реда и да не забравиш да го върнеш.
// Забравеше ли се, следващото издание тръгваше срещу нечий изключен компютър —
// приложението изглежда счупено за всички, а причината е един ред, останал от
// пробата. Освен това самата подсказка не работеше: правилото за сигурност в
// index.html не пускаше 127.0.0.1 и всяка заявка се блъскаше в него мълчаливо.
//
// Сега адресът се избира сам, според това откъде е отворена страницата.
// Продукцията е стойността по подразбиране, а не изключение: приложението за
// компютър се отваря от app://climby и никога не минава по долния път.
window.CLIMBY_BACKEND = 'https://my-project-0gyk.onrender.com';

// Само при разработка: страницата идва от localhost, значи и бекендът е там.
// Сравнява се цялото име на машината, а не част от него — „localhost.example.com“
// свършва другаде и не бива да мине за локална машина.
if (/^(localhost|127\.0\.0\.1|\[::1\])$/.test(location.hostname)) {
  window.CLIMBY_BACKEND = 'http://' + location.hostname + ':8000';
}
